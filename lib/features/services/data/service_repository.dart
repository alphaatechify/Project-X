  static ServiceModel getServiceById(String id) {
    return allServices.firstWhere(
      (s) => s.id == id,
      orElse: () => allServices.firstWhere(
        (s) => s.title.toLowerCase().contains(id.toLowerCase()),
        orElse: () => allServices[0], // default to Dr. House & Care
      ),
    );
  }

